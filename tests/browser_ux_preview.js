async (page) => {
  const origin='http://10.0.3.2:8766';
  const errors=[];const apiCalls=[];const checks=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{if(new URL(request.url()).pathname.startsWith('/api/'))apiCalls.push(request.method()+' '+request.url());});
  const check=(value,label)=>{if(!value)throw new Error(label);checks.push(label);};
  const settled=async()=>{await page.waitForFunction(()=>document.querySelector('#content h1'));await page.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));};
  const nav=async path=>{await page.locator(`#navigation a[href="#/${path}"]`).click();await settled();};
  await page.setViewportSize({width:1440,height:900});
  await page.goto(origin+'/maquette/#/accueil');
  await page.evaluate(()=>{for(const k of Object.keys(localStorage))if(k.startsWith('survie-maquette-v1:'))localStorage.removeItem(k);});
  await page.reload();await settled();
  check((await page.title()).includes('Maquette'),'Entrée séparée et identifiée');
  check(await page.locator('#navigation [aria-current="page"]').count()===1,'Destination active unique');
  await page.getByRole('link',{name:/Encyclopédie illustrée/}).click();await settled();
  check(await page.getByRole('heading',{name:'Explorer cette collection'}).count()===1,'Ouverture directe de collection');
  await page.getByRole('link',{name:/Comprendre le rythme/}).click();await settled();
  await page.getByRole('button',{name:'Ajouter aux favoris de démo'}).click();
  check(await page.getByRole('button',{name:'Retirer des favoris de démo'}).count()===1,'Favori ajouté sans API');
  await page.goBack();await settled();check(await page.getByRole('heading',{name:'Explorer cette collection'}).count()===1,'Retour navigateur collection');
  await page.goForward();await settled();check(await page.getByRole('heading',{name:'Comprendre le rythme des saisons'}).count()===1,'Avance navigateur document');
  await nav('accueil');
  await page.locator('input[name="query"]').fill('mesurer');await page.getByRole('button',{name:'Rechercher',exact:true}).click();await settled();
  check(await page.locator('input[name="query"]').inputValue()==='mesurer','Recherche dans URL');
  await page.getByRole('link',{name:/Apprendre à mesurer une longueur/}).click();await settled();await page.goBack();await settled();
  check(await page.locator('input[name="query"]').inputValue()==='mesurer','Retour avec recherche conservée');
  // Une navigation ajoute une entrée, pas les mesures ou le texte saisi.
  await nav('assistant');
  const before=await page.evaluate(()=>history.length);
  await page.locator('#draft').fill('Mon brouillon à retrouver');
  check(await page.evaluate(()=>history.length)===before,'Pas d’entrée historique par frappe');
  await nav('appareil');await nav('assistant');
  check(await page.locator('#draft').inputValue()==='Mon brouillon à retrouver','Brouillon après changement de page');
  await page.reload();await settled();check(await page.locator('#draft').inputValue()==='Mon brouillon à retrouver','Brouillon après rechargement');
  await page.getByRole('button',{name:'Essayer l’envoi'}).click();
  check((await page.locator('#draft-status').textContent()).includes('Aucun message envoyé'),'Envoi explicitement simulé');
  await nav('appareil');
  await page.getByRole('link',{name:'Téléchargements',exact:true}).click();await settled();
  await page.locator('#scenario').selectOption('verification');await settled();
  check(await page.getByRole('heading',{name:'Vérification du fichier reçu'}).count()===1,'Phase de vérification distincte');
  await page.locator('#scenario').selectOption('inconnu');await settled();
  check(await page.getByRole('heading',{name:'Le suivi est momentanément indisponible'}).count()===1,'Suivi inconnu explicite');
  await page.locator('#scenario').selectOption('transfert');await settled();
  await page.getByRole('button',{name:'Mettre en pause · démo'}).click();await settled();
  check(await page.getByRole('heading',{name:'Téléchargement en pause'}).count()===1,'Pause de démonstration uniquement');
  await nav('bibliotheque');await nav('appareil');
  check(await page.getByRole('heading',{name:'Téléchargement en pause'}).count()===1,'Sous-onglet appareil mémorisé');
  await page.getByRole('link',{name:'Vue d’ensemble',exact:true}).click();await settled();
  await page.locator('summary').filter({hasText:'Voir les mesures détaillées'}).click();
  await nav('accueil');await nav('appareil');
  check(await page.locator('details').evaluate(d=>d.open),'Volet mémorisé');
  await page.locator('#profile-open').click();
  check(await page.locator('#profile-dialog').evaluate(d=>d.open),'Dialogue profil accessible');
  await page.goBack();await settled();check(!await page.locator('#profile-dialog').evaluate(d=>d.open),'Retour ferme le dialogue');
  await page.locator('#profile-open').click();await page.locator('[data-profile="visiteur"]').click();
  await page.waitForFunction(()=>document.querySelector('#profile-name').textContent.includes('Visiteur'));
  await nav('assistant');check(await page.locator('#draft').inputValue()==='','Brouillon isolé par profil fictif');
  await page.locator('#draft').fill('Question du visiteur');
  await page.locator('#profile-open').click();await page.locator('[data-profile="famille"]').click();
  await page.waitForFunction(()=>document.querySelector('#profile-name').textContent.includes('Famille'));
  check(await page.locator('#draft').inputValue()==='Mon brouillon à retrouver','Brouillon Famille préservé');
  await nav('accueil');await page.evaluate(()=>scrollTo(0,380));
  await page.waitForFunction(()=>history.state.scroll>300);
  const oldScroll=await page.evaluate(()=>scrollY);
  await page.getByRole('link',{name:/Encyclopédie illustrée/}).click();await settled();
  await page.goBack();await settled();
  check(Math.abs((await page.evaluate(()=>scrollY))-oldScroll)<8,'Position restaurée au retour');
  await page.reload();await settled();check(Math.abs((await page.evaluate(()=>scrollY))-oldScroll)<8,'Position restaurée au rechargement');
  // Petit téléphone : consultation de la carte et suivi sans commandes complexes.
  await page.setViewportSize({width:390,height:844});await nav('cartes');
  check(await page.locator('.desktop-only').isVisible()===false,'Gestion complexe masquée sur téléphone');
  check(await page.locator('.map-demo').isVisible(),'Carte consultable sur téléphone');
  await nav('appareil');await page.getByRole('link',{name:'Téléchargements',exact:true}).click();await settled();
  check(await page.getByRole('heading',{name:'Votre bibliothèque s’enrichit'}).count()===1,'Suivi visible sur téléphone');
  check(await page.getByRole('button',{name:/Mettre en pause · démo/}).isVisible()===false,'Commandes avancées retirées sur téléphone');
  for(const width of [320,390,760,820,1440]){
    await page.setViewportSize({width,height:900});
    check(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),`Pas de débordement à ${width}px`);
  }
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'/artifacts/maquette-ux-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});await nav('accueil');
  await page.screenshot({path:'/artifacts/maquette-ux-desktop.png',fullPage:true});
  check(errors.length===0,'Pas d’erreur JavaScript : '+errors.join(', '));
  check(apiCalls.length===0,'Aucune requête API ni commande serveur');
  return {checks:checks.length,results:checks};
}
